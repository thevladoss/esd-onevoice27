/**
 * Общая отметка «страница прокручивает себя сама».
 *
 * Плавный переход по пункту меню шлёт десятки событий `scroll` подряд, и хук
 * скрытия шапки читает их как жест вниз: посетитель тапает пункт и остаётся на
 * целевой секции без шапки. Модуль держит окно молчания — его ставит тот, кто
 * дёргает `window.scrollTo`, и читает `useHeaderHide`.
 *
 * Окно в 700 мс покрывает плавный переход через всю страницу. Событие `scrollend`
 * было бы точнее, но Safari его не шлёт, а без запаса шапка уезжала бы ровно там,
 * где переход длиннее всего.
 */
const QUIET_WINDOW = 700;

let quietUntil = 0;

/** Отмечает начало программной прокрутки: следующие 700 мс жестом не считаются. */
export function markProgrammaticScroll(): void {
  quietUntil = performance.now() + QUIET_WINDOW;
}

/** Идёт ли сейчас прокрутка, которую запустила сама страница. */
export function isProgrammaticScroll(): boolean {
  return performance.now() < quietUntil;
}

/**
 * Сбрасывает окно молчания.
 *
 * Нужен тестам: окно живёт 700 мс реального времени, а сценарии идут быстрее, и
 * отметка одного перехода иначе доживала бы до следующего теста.
 */
export function resetProgrammaticScroll(): void {
  quietUntil = 0;
}
