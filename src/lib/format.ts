/** Узкий неразрывный пробел U+202F: разделитель тысяч в счётчиках. */
const THIN_SPACE = "\u202F";

/**
 * Группирует тысячи: 694 даёт «694», 4268 даёт «4 268».
 * Разделитель ставится вручную: у системных форматтеров чисел
 * результат зависит от версии ICU в браузере.
 */
export function formatCount(n: number): string {
  return Math.round(n)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, THIN_SPACE);
}
